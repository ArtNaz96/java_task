public class Calculator {

    public int numberAddition(int a, int b) {
        return a + b;
    }

    public int numberSubtraction(int a, int b) {
        return a - b;
    }

    public int numberMultiplication(int a, int b) {
        return a * b;
    }

    public int numberDivision(int a, int b) {
        return a / b;
    }
}